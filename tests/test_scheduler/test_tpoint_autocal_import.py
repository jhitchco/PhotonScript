def test_astap_solve_adapter(tmp_path):
    from astropy.io import fits
    import numpy as np
    f = tmp_path / "frame.fit"
    fits.PrimaryHDU(np.zeros((100, 150), dtype=np.uint16)).writeto(f)
    seen = {}

    def runner(p, fov, hint, r, t):
        seen.update(fov=fov, hint=hint, r=r)
        return {"PLTSOLVD": "T", "CRVAL1": "307.5", "CRVAL2": "40.25",
                "CD1_1": "-1.3e-4", "CD1_2": "0", "CD2_1": "0", "CD2_2": "1.3e-4"}
    cfg = _cfg(tmp_path)
    out = tal.astap_solve(cfg, str(f), 0.472, (307.0, 40.0), runner=runner)
    assert out["ra"] == pytest.approx(307.5) and out["dec"] == pytest.approx(40.25)
    assert seen["fov"] == pytest.approx(100 * 0.472 / 3600)
    assert seen["hint"] == (307.0, 40.0) and seen["r"] == 10.0
    assert "error" in tal.astap_solve(cfg, str(tmp_path / "missing.fit"), 0.472, None,
                                      runner=runner)
    nope = tal.astap_solve(cfg, str(f), 0.472, None,
                           runner=lambda *a: {"PLTSOLVD": "F"})
    assert nope == {"error": "ASTAP did not solve"}
    hdr = tal.fits_header(str(f))
    assert hdr["NAXIS2"] == 100 and hdr["PIERSIDE"] is None


