def test_through_the_pole_matches_the_real_files():
    """Every real sample 1 h or more from the meridian: beyond the pole
    (|observed Dec| > 90) exactly when HA < 0, the side encode_observed
    flips; un-flipping gives the mount back within a degree of the star."""
    n = 0
    for f in FIX.glob("*/*in.dat"):
        for s in cov.parse(_real(f))["samples"]:
            ha = ti.wrap_ha(s["lst_h"] - s["star_ra_h"])
            if abs(ha) < 1.0:
                continue
            n += 1
            flipped = abs(s["scope_dec"]) > 90
            assert flipped == ti.beyond_pole(ha)
            if flipped:   # undo: mount RA / Dec, then encode again
                ra = (s["scope_ra_h"] - 12) % 24
                dec = 180 - s["scope_dec"] if s["scope_dec"] > 0 else -180 - s["scope_dec"]
                assert abs(dec - s["star_dec"]) < 1.0
                e = ti.encode_observed(ra, dec, True)
                assert e[0] == pytest.approx(s["scope_ra_h"] % 24, abs=1e-9)
                assert e[1] == pytest.approx(s["scope_dec"], abs=1e-9)
    assert n > 300
    assert ti.encode_observed(10.0, 20.0, False) == (10.0, 20.0)
    assert ti.encode_observed(23.0, -20.0, True) == (11.0, -160.0)


def test_apparent_place():
    # 2026.8: precession alone moves RA 310, Dec +45 by about +0.23 deg in
    # RA and +0.10 deg in Dec (erfa: precession, nutation, aberration)
    ra, dec = ti.j2000_to_apparent(310.0 / 15, 45.0, datetime(2026, 10, 21, 3, 0))
    assert 0.22 < ra * 15 - 310.0 < 0.24 and 0.09 < dec - 45.0 < 0.11
    # at J2000 itself only nutation + aberration remain (well under 1')
    ra0, dec0 = ti.j2000_to_apparent(310.0 / 15, 45.0, datetime(2000, 1, 1, 12, 0))
    assert abs(ra0 * 15 - 310.0) * math.cos(math.radians(45)) < 1 / 60
    assert abs(dec0 - 45.0) < 1 / 60


