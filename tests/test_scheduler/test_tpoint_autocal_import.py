# ------------------------------------------------------------- the loop

def _sol(i):
    """Point i's fake truth: the J2000 centre and the mount reading 2'
    away, LST so that HA = +2 h (west, not through the pole)."""
    ra = 20.0 + 0.1 * i
    return {"ra": ra, "dec": 10.0 + 5 * i, "mra": ra + 0.002, "mdec": 10.0 + 5 * i - 0.03,
            "lst": ra + 2.0}


class ImportSky(FakeSky):
    def __init__(self, files, il=lambda n: True, mount_ok=True, **kw):
        super().__init__(files, **kw)
        self.il = il
        self.mount_ok = mount_ok

    def run(self, js):
        if "ImageLink.execute()" in js:
            self.calls.append("imagelink")
            self.scripts.append(js)
            n = self.calls.count("imagelink")
            if not self.il(n):
                return {"exec_error": None, "succeeded": "0", "error_code": "212",
                        "error_text": "Process aborted. Error _ 212."}
            s = _sol(n)
            return {"exec_error": None, "succeeded": "1", "error_code": "0",
                    "ra_j2000_h": str(s["ra"]), "dec_j2000_d": str(s["dec"]),
                    "image_scale": "0.472", "solution_rms": "0.6", "image_stars": "80"}
        if "ComputeLocalSiderealTime" in js:
            self.calls.append("mount_snapshot")
            self.scripts.append(js)
            if not self.mount_ok:
                return {"connected": None}
            s = _sol(self.calls.count("mount_snapshot"))
            return {"connected": "1", "ra_h": str(s["mra"]), "dec_d": str(s["mdec"]),
                    "az": "250", "alt": "45", "tracking": "1", "lst_h": str(s["lst"]),
                    "jd": "2461334.6"}
        kind(js)
        return super().run(js)


def _run(tmp_path, solver="imagelink", il=lambda n: True, astap=None,
         mount_ok=True, import_path=None, ask_answers=None, ref=True,
         csv_name="x_tpoint_autocal.csv", roots=(), weather=None):
    clock = Clock()
    files = Files(561)
    sky = ImportSky(files, il=il, mount_ok=mount_ok)
    nina = FakeNina(clock)
    out: list[str] = []
    asked: list[str] = []
    seen_astap: list = []

    def ask(p):
        asked.append(p)
        return "yes" if "Backup done" in p else "no"

    def fake_astap(path, scale, hint):
        seen_astap.append((path, scale, hint))
        return astap(len(seen_astap)) if astap else {"error": "no"}

    imp = import_path or str(tmp_path / "tpoint_import" / "20261021T030000Z_west.dat")
    deps = tal.Deps(sky=sky, nina=nina, sched=FakeSched(), count=files.count,
                    list_files=lambda: {"files": [
                        {"rel": r"TPoint\Super Model Indat.dat",
                         "path": r"C:\sky\Super Model Indat.dat", "size": 1}]},
                    ask=ask, say=out.append, sleep=clock.sleep, mono=clock.mono,
                    now=clock.now, copy=lambda s, d: None,
                    astap=fake_astap, import_ref=(lambda: _real()) if ref else None,
                    forbidden_roots=list(roots), weather=weather)
    opts = tal.Opts(csv_path=str(tmp_path / "runs" / csv_name),
                    backup_root=str(tmp_path / "bk"), solver=solver, import_path=imp)
    res = tal.run_loop(_cfg(tmp_path), _PTS, deps, opts)
    return res, sky, nina, out, asked, seen_astap, imp


def test_import_happy_path_and_round_trip(tmp_path):
    res, sky, nina, out, asked, seen, imp = _run(tmp_path)
    assert res["status"] == "done", res["reason"]
    assert res["add"] == "import" and res["solved"] == 3 and res["import_lines"] == 3
    assert (res["samples_before"], res["samples_after"]) == (561, 561)
    assert res["camera_returned"] is True and nina.calls == ["disconnect", "connect"]
    c = sky.calls
    assert "automap" not in c and "ails_setup" not in c and seen == []
    assert c.count("imagelink") == 3 and c.count("mount_snapshot") == 3
    i = c.index("expose")
    assert c[i + 1] == "mount_snapshot" and c.index("imagelink") > c.index("expose_poll")
    assert len(asked) == 1                        # only the backup question
    text = "\n".join(out)
    assert "Import Pointing Data" in text and imp in text
    assert text.isascii() and "\u2014" not in text

    raw = Path(imp).read_bytes().decode("ascii")
    assert raw.count("\r\n") == 5 + 3 and "\n" not in raw.replace("\r\n", "")
    assert raw.startswith("!TheSky Version 10.5.0 Build 14139 (64 bit)\r\nParamount MX\r\n"
                          ":NODA\r\n:EQUAT\r\n+31 54 25 2026 10 15 29.31 870.00 1300.00  0.50")
