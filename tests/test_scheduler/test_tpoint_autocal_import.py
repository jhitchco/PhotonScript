def _regenerate(text: str) -> str:
    """Parse a real in.dat with the repo's parsers and write it back with
    tpoint_import."""
    parsed = cov.parse(text)
    raw = [ln.split() for ln in text.splitlines()
           if re.match(r"^\d\d \d\d \d\d\.\d{4} ", ln)]
    lines = [ti.obs_line(s["star_ra_h"], s["star_dec"], s["scope_ra_h"],
                         s["scope_dec"], s["lst_h"], t[3].startswith("-"),
                         t[9].startswith("-"))
             for s, t in zip(parsed["samples"], raw)]
    site = [ln for ln in text.splitlines() if re.match(r"^[+-]\d\d \d\d \d\d \d{4} ", ln)][0]
    y, m, d = (int(x) for x in site.split()[3:6])
    return ti.render(ti.header_lines(datetime(y, m, d), ref=ti.reference_header(text)),
                     lines)


