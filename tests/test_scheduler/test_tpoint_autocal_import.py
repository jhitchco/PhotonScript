    d = tf.parse_data(raw)
    assert d["points"] == 3 and d["options"] == ["NODA", "EQUAT"]
    back = cov.parse(raw)["samples"]
    for k, (s, row) in enumerate(zip(back, res["rows"]), 1):
        want = _sol(k)
        assert row["added"] is True and row["solved_by"] == "imagelink"
